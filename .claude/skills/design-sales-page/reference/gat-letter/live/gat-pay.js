/* Great Again T: the one-page order form (card fields are Stripe Elements), the thank-you page and the account page.
   Generated by build_live.py: edit live/gat-pay.js, never the theme copy. The server side is gat-checkout.js. */
(function () {
  'use strict';
  var CFG = /*CFG*/{};
  var body = document.body;
  var page = body.getAttribute('data-gat') || '';
  var API = CFG.api || '';
  var $ = function (s, r) { return (r || document).querySelector(s); };
  var $$ = function (s, r) { return Array.prototype.slice.call((r || document).querySelectorAll(s)); };
  function track(name, props) { try { if (window.posthog && window.posthog.capture) window.posthog.capture(name, props || {}); } catch (e) {} }
  function store(k, v) { try { if (v === undefined) return window.localStorage.getItem(k); window.localStorage.setItem(k, v); } catch (e) { return null; } }
  function param(name) { var m = new RegExp('[?&]' + name + '=([^&#]*)').exec(window.location.search); return m ? decodeURIComponent(m[1].replace(/\+/g, ' ')) : ''; }
  function api(path, data) {
    var opt = data === undefined ? {} : { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) };
    return fetch(API + path, opt).then(function (r) {
      return r.json().catch(function () { return {}; }).then(function (j) { if (!r.ok) { var e = new Error(j.error || 'failed'); e.field = j.field; e.status = r.status; throw e; } return j; });
    });
  }
  function show(el, on) { if (el) el.hidden = !on; }
  function testBar(mode) {
    if (mode !== 'test' || $('.op-test')) return;
    var b = document.createElement('div');
    b.className = 'op-test';
    b.innerHTML = 'TEST MODE. No real charge. <span>Card 4242 4242 4242 4242,</span> <span>any future date, any CVV.</span>';
    body.insertBefore(b, body.firstChild);
  }

  /* Where the visitor came from (ad click id and campaign tags), kept so the order can carry it. Never a name or an answer. */
  try {
    var seen = JSON.parse(store('gat_attr') || '{}'), changed = false;
    ['gclid', 'utm_source', 'utm_medium', 'utm_campaign', 'utm_content', 'utm_term'].forEach(function (k) { var v = param(k); if (v) { seen[k] = v.slice(0, 200); changed = true; } });
    if (changed) store('gat_attr', JSON.stringify(seen));
  } catch (e) {}

  /* ---------------- one-page order form ---------------- */
  if (page === 'order' && body.classList.contains('op')) {
    var main = $('main.co'), form = $('#op-form'), btn = $('#op-pay'), label = $('#op-pay-label'), agree = $('#agree'), err = $('#co-err');
    var option = function () { var r = $('input[name="gat-option"]:checked'); return r ? r.value : 'trial'; };
    var say = function (msg) { err.textContent = msg || ''; err.hidden = !msg; };
    var paint = function () {
      var o = option();
      main.classList.toggle('is-trial', o === 'trial'); main.classList.toggle('is-single', o === 'single');
      $$('.opt').forEach(function (l) { l.classList.toggle('on', $('input', l).checked); });
      say('');
    };
    $$('input[name="gat-option"]').forEach(function (r) {
      r.addEventListener('change', function () { paint(); track('gat_option_select', { option: option(), flow: 'one-page' }); });
    });
    if (/[?&]option=single(&|$)/.test(window.location.search)) { var s1 = $('input[value="single"]'); if (s1) s1.checked = true; }
    paint();
    if (agree) agree.addEventListener('change', function () { if (agree.checked) say(''); });

    var val = function (id) { var el = $('#' + id); return el ? el.value.trim() : ''; };
    var fieldOf = function (id) { var el = $('#' + id); return el ? (el.closest('.field') || $('#' + id + '-f')) : null; };
    var mark = function (id, msg) {
      var f = fieldOf(id); if (!f) return;
      var old = $('.ferr', f); if (old) old.remove();
      f.classList.toggle('bad', !!msg);
      if (msg) { var s = document.createElement('small'); s.className = 'ferr'; s.textContent = msg; f.appendChild(s); }
    };
    $$('input, select', form).forEach(function (el) { el.addEventListener('input', function () { if (el.id) mark(el.id, ''); }); });

    var billdiff = $('#op-billdiff'), bill = $('#op-bill');
    billdiff.addEventListener('change', function () { bill.hidden = !billdiff.checked; });

    /* "Name on card" follows the shipping name until the buyer types their own */
    var nameEl = $('#op-name'), nameTouched = false;
    nameEl.addEventListener('input', function () { nameTouched = true; });
    ['op-first', 'op-last'].forEach(function (id) {
      $('#' + id).addEventListener('input', function () { if (!nameTouched) { nameEl.value = (val('op-first') + ' ' + val('op-last')).trim(); if (nameEl.value) mark('op-name', ''); } });
    });

    var stripe = null, card = {}, state = { 'op-card-number': {}, 'op-card-exp': {}, 'op-card-cvc': {} }, orderId = null, busy = false, started = false;
    var closed = function (why) {
      say('Ordering is not open yet. Please email ' + CFG.support + ' and we will let you know when it is.');
      btn.disabled = true; track('gat_checkout_error', { reason: why, flow: 'one-page' });
    };
    var loadScript = function (src) {
      return new Promise(function (ok, no) { var s = document.createElement('script'); s.src = src; s.onload = ok; s.onerror = no; document.head.appendChild(s); });
    };
    var ready = api('/api/gat/config').then(function (c) {
      if (!c.open || !c.publishableKey) throw new Error('closed');
      /* the page never takes a price it does not show */
      if (c.prices.single !== CFG.singlePrice || c.prices.shipping !== CFG.shipping || c.prices.monthly !== CFG.monthly) throw new Error('price');
      testBar(c.mode);
      return loadScript('https://js.stripe.com/v3/').then(function () {
        stripe = window.Stripe(c.publishableKey);
        var els = stripe.elements({ fonts: [{ cssSrc: 'https://fonts.googleapis.com/css2?family=Archivo:wght@400;500&display=swap' }] });
        var style = { base: { fontFamily: 'Archivo, Arial, sans-serif', fontSize: '16px', color: '#1f2827', '::placeholder': { color: '#9b9a92' } }, invalid: { color: '#a8281c' } };
        var make = function (type, id, opts) {
          var e = els.create(type, Object.assign({ style: style }, opts || {}));
          e.mount('#' + id);
          e.on('change', function (ev) { state[id] = { complete: ev.complete, error: ev.error && ev.error.message }; mark(id, ev.error ? ev.error.message : ''); if (!busy) say(''); });
          e.on('focus', function () { $('#' + id).classList.add('focus'); if (!started) { started = true; track('gat_payment_start', { option: option() }); } });
          e.on('blur', function () { $('#' + id).classList.remove('focus'); });
          return e;
        };
        card.number = make('cardNumber', 'op-card-number', { showIcon: true, placeholder: '1234 1234 1234 1234', disableLink: true });
        card.exp = make('cardExpiry', 'op-card-exp');
        card.cvc = make('cardCvc', 'op-card-cvc', { placeholder: '123' });
      });
    }).catch(function (x) { closed(x && x.message === 'price' ? 'price-mismatch' : 'not-open'); throw x; });
    ready.catch(function () {});

    var checks = [
      ['op-first', function (v) { return v ? '' : 'Please enter your first name.'; }],
      ['op-last', function (v) { return v ? '' : 'Please enter your last name.'; }],
      ['op-email', function (v) { return /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(v) ? '' : 'Please enter a valid email address.'; }],
      ['op-phone', function (v) { return v.replace(/\D/g, '').length >= 10 ? '' : 'Please enter your phone number.'; }],
      ['op-addr1', function (v) { return v.length >= 3 ? '' : 'Please enter your address.'; }],
      ['op-city', function (v) { return v.length >= 2 ? '' : 'Please enter your city.'; }],
      ['op-state', function (v) { return v ? '' : 'Please choose your state.'; }],
      ['op-zip', function (v) { return /^\d{5}(-\d{4})?$/.test(v) ? '' : 'Please enter a 5 digit ZIP code.'; }]
    ];
    var billChecks = [
      ['op-b-addr1', function (v) { return v.length >= 3 ? '' : 'Please enter your billing address.'; }],
      ['op-b-city', function (v) { return v.length >= 2 ? '' : 'Please enter your billing city.'; }],
      ['op-b-state', function (v) { return v ? '' : 'Please choose your billing state.'; }],
      ['op-b-zip', function (v) { return /^\d{5}(-\d{4})?$/.test(v) ? '' : 'Please enter a 5 digit billing ZIP code.'; }]
    ];
    var cardChecks = [['op-card-number', 'Please enter your card number.'], ['op-card-exp', 'Please enter the expiration date.'], ['op-card-cvc', 'Please enter the CVV.']];
    var serverField = { firstName: 'op-first', lastName: 'op-last', email: 'op-email', phone: 'op-phone', 'shipping.address1': 'op-addr1', 'shipping.city': 'op-city',
      'shipping.state': 'op-state', 'shipping.zip': 'op-zip', 'billing.address1': 'op-b-addr1', 'billing.city': 'op-b-city', 'billing.state': 'op-b-state', 'billing.zip': 'op-b-zip' };

    var validate = function () {
      var first = null, list = checks.concat(billdiff.checked ? billChecks : []).concat([['op-name', function (v) { return v ? '' : 'Please enter the name on your card.'; }]]);
      list.forEach(function (c) { var m = c[1](val(c[0])); mark(c[0], m); if (m && !first) first = { id: c[0], msg: m }; });
      cardChecks.forEach(function (c) {
        var st = state[c[0]], m = st.complete ? '' : (st.error || c[1]);
        mark(c[0], m); if (m && !first) first = { id: c[0], msg: m, el: c[0] === 'op-card-number' ? card.number : c[0] === 'op-card-exp' ? card.exp : card.cvc };
      });
      return first;
    };
    var setBusy = function (on) {
      busy = on; btn.disabled = on; btn.classList.toggle('busy', on);
      label.textContent = on ? 'Placing Your Order' : 'Complete My Order';
    };

    form.addEventListener('submit', function (e) {
      e.preventDefault();
      if (busy) return;
      var o = option();
      say('');
      var bad = validate();
      if (bad) {
        say(bad.msg);
        if (bad.el) bad.el.focus(); else { var el = $('#' + bad.id); el.focus(); }
        var f = fieldOf(bad.id); if (f && f.scrollIntoView) f.scrollIntoView({ block: 'center', behavior: 'smooth' });
        track('gat_checkout_error', { option: o, reason: 'field', field: bad.id.replace('op-', ''), flow: 'one-page' });
        return;
      }
      if (o === 'trial' && !agree.checked) {
        say('Please tick the box above to agree to the terms of the offer.');
        agree.focus();
        track('gat_checkout_error', { option: o, reason: 'terms-box', flow: 'one-page' });
        return;
      }
      setBusy(true);
      var value = o === 'trial' ? CFG.shipping / 100 : CFG.singlePrice / 100;
      track('gat_checkout_start', { option: o, value: value, currency: 'USD', flow: 'one-page' });
      var attr = {};
      try { attr = JSON.parse(store('gat_attr') || '{}'); } catch (x) {}
      try { if (window.posthog && window.posthog.get_distinct_id) attr.ph = window.posthog.get_distinct_id(); } catch (x) {}
      var ship = { address1: val('op-addr1'), address2: val('op-addr2'), city: val('op-city'), state: val('op-state'), zip: val('op-zip') };
      var billing = billdiff.checked ? { address1: val('op-b-addr1'), address2: val('op-b-addr2'), city: val('op-b-city'), state: val('op-b-state'), zip: val('op-b-zip') } : null;
      var b = billing || ship;
      ready.then(function () {
        return api('/api/gat/order', { option: o, orderId: orderId || undefined, firstName: val('op-first'), lastName: val('op-last'), email: val('op-email'),
          phone: val('op-phone'), shipping: ship, billing: billing, agree: o === 'trial' ? agree.checked : false, sms: $('#op-sms').checked, attribution: attr });
      }).then(function (r) {
        orderId = r.orderId;
        return stripe.confirmCardPayment(r.clientSecret, { payment_method: { card: card.number, billing_details: { name: val('op-name'), email: val('op-email'), phone: val('op-phone'),
          address: { line1: b.address1, line2: b.address2 || undefined, city: b.city, state: b.state, postal_code: b.zip, country: 'US' } } } });
      }).then(function (res) {
        if (res.error) { var ce = new Error(res.error.message || 'Your card was declined.'); ce.card = res.error.code || res.error.type; throw ce; }
        track('gat_payment_done', { option: o, flow: 'one-page' });
        window.location.href = CFG.links.thanks + (CFG.links.thanks.indexOf('?') < 0 ? '?' : '&') + 'o=' + encodeURIComponent(orderId);
      }).catch(function (x) {
        setBusy(false);
        if (x && x.field && serverField[x.field]) { mark(serverField[x.field], x.message); var el2 = $('#' + serverField[x.field]); if (el2) el2.focus(); }
        var known = x && (x.card || x.status === 400 || x.status === 402 || x.status === 429 || x.status === 503);
        say(known ? x.message : 'Something went wrong and your order was not placed. Please try again, or email ' + CFG.support + '.');
        track('gat_checkout_error', { option: o, reason: x && x.card ? 'card' : x && x.status ? 'server-' + x.status : 'network', code: x && x.card || undefined, flow: 'one-page' });
      });
    });
  }

  /* ---------------- thank-you page ---------------- */
  if (page === 'thanks') {
    var id = param('o'), ty = $('#ty'), tries = 0;
    var miss = function () { show($('#ty-wait'), false); show($('#ty-miss'), true); };
    var report = function (d) {
      /* once per order, ever: the server says whether this is the first time this order has been reported */
      api('/api/gat/order/' + id + '/tracked', {}).then(function (t) {
        if (!t.first) return;
        var props = { order_id: d.orderName || id, value: d.total, currency: d.currency, option: d.option, flow: 'one-page' };
        if (d.mode !== 'live') { track('gat_purchase_test', props); return; }
        track('gat_purchase', props);
        var cp = window.Shopify && window.Shopify.customerPrivacy;
        if (cp && cp.saleOfDataAllowed && cp.saleOfDataAllowed() === false) return;
        var g = document.createElement('script'); g.async = true; g.src = 'https://www.googletagmanager.com/gtag/js?id=' + CFG.ads.id; document.head.appendChild(g);
        window.dataLayer = window.dataLayer || [];
        var gtag = function () { window.dataLayer.push(arguments); };
        gtag('js', new Date()); gtag('config', CFG.ads.id);
        gtag('event', 'conversion', { send_to: CFG.ads.id + '/' + CFG.ads.label, value: d.total, currency: d.currency, transaction_id: d.orderName || id });
      }).catch(function () {});
    };
    var draw = function (d) {
      testBar(d.mode);
      ty.classList.toggle('is-trial', d.option === 'trial'); ty.classList.toggle('is-single', d.option === 'single');
      $('#ty-title').textContent = 'Thank you' + (d.firstName ? ', ' + d.firstName : '') + '. Your order is confirmed.';
      $('#ty-order').textContent = d.orderName || 'being prepared';
      if ($('#ty-first')) $('#ty-first').textContent = d.firstCharge || 'about 30 days from today';
      show($('#ty-wait'), false); show($('#ty-done'), true);
      /* the hook for the one-click upsells (GAT Upsell 1 to 4): they mount here, on the saved card, when they are built */
      var up = $('#gat-upsell'); if (up) up.setAttribute('data-order', id);
      try { document.dispatchEvent(new CustomEvent('gat:order-confirmed', { detail: { order: id, option: d.option } })); } catch (e) {}
      report(d);
    };
    var poll = function () {
      api('/api/gat/order/' + id).then(function (d) {
        if (d.status === 'paid' && (d.orderName || tries >= 6)) return draw(d);
        if (++tries > 14) return d.status === 'paid' ? draw(d) : miss();
        window.setTimeout(poll, 1500);
      }).catch(function (x) { if (x && x.status === 404) return miss(); if (++tries > 6) return miss(); window.setTimeout(poll, 2000); });
    };
    if (/^[a-f0-9]{24}$/.test(id)) poll(); else miss();
  }

  /* ---------------- account page (cancel, skip a month, update the card) ---------------- */
  if (page === 'account') {
    var oid = param('o'), key = param('k'), aerr = $('#ac-err'), ok = $('#ac-ok');
    var asay = function (m) { aerr.textContent = m || ''; aerr.hidden = !m; };
    var note = function (m) { ok.textContent = m || ''; ok.hidden = !m; };
    var paintAcct = function (d) {
      testBar(d.mode);
      show($('#ac-wait'), false);
      show($('#ac-on'), d.active); show($('#ac-off'), !d.active && d.option === 'trial'); show($('#ac-single'), d.option === 'single');
      if (!d.active) return;
      $('#ac-hello').textContent = (d.firstName ? d.firstName + ', here' : 'Here') + ' is your monthly delivery. You can change it at any time.';
      $('#ac-status').textContent = d.status === 'past_due' ? 'Card declined' : 'Active';
      $('#ac-next').textContent = d.nextCharge || '';
      $('#ac-skip').hidden = !d.canSkip;
      $('#ac-skipnote').textContent = d.canSkip ? 'Skipping moves your next bottle and charge to ' + d.nextChargeIfSkipped + '.' : '';
    };
    var act = function (action, button, done) {
      asay(''); note('');
      $$('.acct-btn').forEach(function (b) { b.disabled = true; });
      api('/api/gat/account/' + oid + '/' + action, { k: key }).then(function (d) {
        $$('.acct-btn').forEach(function (b) { b.disabled = false; });
        track('gat_account_' + action);
        if (d.url) { window.location.href = d.url; return; }
        show($('#ac-confirm'), false);
        paintAcct(d); if (done) note(done(d));
      }).catch(function (x) {
        $$('.acct-btn').forEach(function (b) { b.disabled = false; });
        asay(x && x.status && x.status < 500 ? x.message : 'Something went wrong. Please try again, or email ' + CFG.support + '.');
      });
    };
    if (!/^[a-f0-9]{24}$/.test(oid) || !/^[a-f0-9]{32}$/.test(key)) { show($('#ac-wait'), false); show($('#ac-miss'), true); }
    else {
      api('/api/gat/account/' + oid + '?k=' + key).then(paintAcct).catch(function () { show($('#ac-wait'), false); show($('#ac-miss'), true); });
      $('#ac-skip').addEventListener('click', function () { act('skip', this, function (d) { return 'Done. Your next bottle and charge moved to ' + d.nextCharge + '.'; }); });
      $('#ac-card').addEventListener('click', function () { act('card', this); });
      $('#ac-cancel').addEventListener('click', function () { show($('#ac-confirm'), true); $('#ac-yes').focus(); });
      $('#ac-no').addEventListener('click', function () { show($('#ac-confirm'), false); });
      $('#ac-yes').addEventListener('click', function () { act('cancel', this); });
    }
  }
})();
