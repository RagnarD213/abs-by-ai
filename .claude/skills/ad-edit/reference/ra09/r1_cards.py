#!/usr/bin/env python3
"""RA-09 round 1: every opaque card of the plan, 9:16, exactly its plan frame count -> r1/cards/<name>.mp4 + r1/cards/clips.json

  H1  library A0014 (AI, 9:16): a ripped man flexes and laughs beside a humanoid robot in a gym, "Do you think AI is changing the
      world?". Source 0.00 s on, before he lowers his arm and looks down (about 2.2 s). Fills the frame. AI-GENERATED by person mask.
  G1  the prospect's AI goal picture (RA-04 R5 lake-dock man, B0550's result), Soft Blue photo scene, AI-GENERATED,
      "I'm not just talking about an AI-generated picture." (RA-12 R2's approved G1 treatment, Dan 2026-10-17/21)
  W1  Dan's own ab wheel rollout by the pool (library B0427, real footage), "using AI to get real six-pack abs in real life": RA-12
      R2's approved W1 exactly (2.50 s in, full-height 1280x1080 card at x 540, the same grade). Real moving footage: no label.
  P1  the prospect's real absbyai.com generation (B0550, 60 fps) at 1.0x from the Generate tap: his AI-generated before photo
      under the scan ("upload a picture of where you're at now and use AI to generate an image of you"), then his AI goal
      picture full card with a push ("with your dream body in seconds, completely free"). AI-GENERATED from B0550 frame 39 on.
  T1  the approved app tour B0544: the AI Trainer's Push-Up demo on "personalized workout", the Macro Tracker on "nutrition plan".
  I1  RA-07 R6's approved A1 card, unchanged pixels (A0179: the man in a sling walks into the gym, then the leg press), 62 frames.
  G2  RA-07 R6's approved G1 card (gym CLOSED, he opens his palms), 14 frames, unchanged.
  M1  RA-07 R6's approved M1 card (same man curls a dumbbell at home, library A0196), 60 frames, unchanged.
"""
import json, os, shutil, subprocess, sys
import numpy as np
from PIL import Image
sys.path.insert(0, "/Volumes/Expansion/_edit_work/RA-09")
import ra01lib as L
import s63_stills as S63
SH = f"{L.REPO}/.claude/skills/_shared"
sys.path.insert(0, SH); sys.path.insert(0, SH + "/hyperframes")
import softblue as SB
import composite as CP
import vertical as V

FPS = L.FPS; FPSS = "30000/1001"; W, H = 1080, 1920
PL = json.load(open(os.environ.get("PLAN", "beats.json"))); CB = {c["name"]: c for c in PL["cards"]}
WORDS = json.load(open("words_aligned.json"))["words"]
LIB = "/Volumes/Extreme/_asset_library_stage/Abs By AI - Video Asset Library"
A0014 = f"{LIB}/04 AI-Generated Clips/concepts-and-gags/A0014_ripped-man-flexes-next-to-robot_9x16_5s.mp4"
B0427 = f"{LIB}/03 B-Roll - Real Footage/dan-filmed/B0427_dan-ab-wheel-rollout-poolside-profile_16x9_8s.mp4"
B0550 = f"{LIB}/03 B-Roll - Real Footage/screen-recordings/B0550_app-generate-goal-image-heavier-white-man-lake-dock_1320x2868_42s.mp4"
PGOAL = "/Volumes/Extreme/_edit_work/ra04/round5/after_white_man.jpg"
REUSE = {"I1": ("r1/reuse/ra07_A1.mp4", 62), "G2": ("r1/reuse/ra07_G1.mp4", 14), "M1": ("r1/reuse/ra07_M1.mp4", 60)}
GRADE_W1 = "eq=gamma=1.15:saturation=0.78,colorchannelmixer=rr=1.0:gg=1.0:bb=1.15"   # RA-12 R2's approved W1 grade
OUT = "r1/cards"; PLT = os.path.abspath("r1/plates"); os.makedirs(OUT, exist_ok=True); os.makedirs("r1/media", exist_ok=True)
ENC = ["-c:v", "libx264", "-preset", "medium", "-crf", "15", "-pix_fmt", "yuv420p", "-r", FPSS, "-colorspace", "bt709",
       "-color_primaries", "bt709", "-color_trc", "bt709", "-color_range", "tv", "-x264-params", "keyint=30:min-keyint=1:scenecut=0"]
D709 = "scale=in_color_matrix=bt709:in_range=tv:out_color_matrix=bt709"


def media(name, path, t0, n, vf, wh, grade=None):
    vf = vf + ("," + grade if grade else "")
    out = f"r1/media/{name}.mp4"
    subprocess.run([L.FF, "-nostdin", "-y", "-v", "error", "-ss", f"{t0:.3f}", "-t", f"{n / FPS + 0.3:.3f}", "-i", path,
                    "-vf", f"fps={FPSS},{vf},scale={wh[0]}:{wh[1]}:flags=lanczos,setsar=1", "-frames:v", str(n)] + ENC + [out], check=True)
    return out


def frames(path, wh, n):
    p = subprocess.Popen([L.FF, "-nostdin", "-v", "error", "-i", path, "-vf", f"{D709},format=rgb24", "-frames:v", str(n),
                          "-f", "rawvideo", "-"], stdout=subprocess.PIPE)
    sz = wh[0] * wh[1] * 3
    for k in range(n):
        b = p.stdout.read(sz); assert len(b) == sz, (path, k, n)
        yield np.frombuffer(b, np.uint8).reshape(wh[1], wh[0], 3)
    p.stdout.close(); p.wait()


def writer(out):
    return subprocess.Popen([L.FF, "-nostdin", "-y", "-v", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{W}x{H}",
                             "-framerate", FPSS, "-i", "-", "-vf", "scale=out_color_matrix=bt709:out_range=tv,format=yuv420p"] + ENC + [out],
                            stdin=subprocess.PIPE)


def word_after(a, prefix):
    return next(w["t"] for w in WORDS if w["t"] > a and w["w"].strip().lower().strip(".,?!").startswith(prefix))


meta = json.load(open(f"{OUT}/clips.json")) if os.path.exists(f"{OUT}/clips.json") else {}
only = set(sys.argv[1:]); want = lambda k: (not only or k in only) and k in CB

if want("H1"):
    n = CB["H1"]["frames"]
    assert n / FPS <= 57.5 / 24, ("H1 runs past the verified window 0-57 (clipcheck + frame-reviewer)", n / FPS)
    # 716x1284 -> cover 1080x1920: scale to 1080 wide (1937 tall), keep the top (his head sits high), crop 1920
    m = media("H1", A0014, 0.0, n, "scale=1080:-2:flags=lanczos,crop=1080:1920:0:0", (W, H))
    fr = list(frames(m, (W, H), n))
    A = L.Aspect("9x16")
    masks = [L.person_mask(Image.fromarray(fr[k])) for k in (0, n // 2, n - 1)]
    chip = SB.disclosure(Image.new("RGBA", (W, H)), "AI-GENERATED", xy=(0, 0))
    # measure the chip's size from a dry draw: softblue.disclosure returns its box
    cw_, ch_ = (int(round(chip[2] - chip[0])), int(round(chip[3] - chip[1]))) if isinstance(chip, tuple) and len(chip) == 4 else (300, 64)
    (cx, cy), why = L.place_chip(masks, (cw_, ch_), A, box=(60, 200, 940, 1340))
    e = writer(f"{OUT}/H1.mp4")
    for f in fr:
        im = Image.fromarray(f).convert("RGBA"); SB.disclosure(im, "AI-GENERATED", xy=(cx, cy))
        e.stdin.write(np.asarray(im.convert("RGB")).tobytes())
    e.stdin.close(); e.wait()
    meta["H1"] = dict(asset="A0014", src=A0014, src_in=0.0, frames=n, hole=[0, 0, W, H], chip="AI-GENERATED", chip_xy=[cx, cy], chip_why=why)
    print("H1", n, "frames, chip at", (cx, cy), why, flush=True)

if want("W1"):
    n = CB["W1"]["frames"]
    scene, hole = V.media_card_scene("P_W1", n / FPS + 0.2, 1280 / 1080, label=None)
    V.build([scene], PLT, render=True, snap=1.0)
    x0, y0, x1, y1 = hole; wh = (x1 - x0, y1 - y0)
    m = media("W1", B0427, 2.50, n, "crop=1280:1080:540:0", wh, GRADE_W1)
    e = writer(f"{OUT}/W1.mp4")
    for f, ov in zip(frames(m, wh, n), CP.reader(f"{PLT}/renders/P_W1.mov", 0, n, True, (W, H))):
        c = np.zeros((H, W, 3), np.uint8); c[y0:y1, x0:x1] = f
        e.stdin.write(np.ascontiguousarray(CP.over(c, ov)).tobytes())
    e.stdin.close(); e.wait()
    meta["W1"] = dict(asset="B0427", src=B0427, src_in=2.50, frames=n, crop=[1280, 1080, 540, 0], hole=hole, chip=None, grade=GRADE_W1)
    print("W1", n, "frames, hole", hole, flush=True)

if want("G1"):
    n = CB["G1"]["frames"]; e = writer(f"{OUT}/G1.mp4")
    for i in range(n):
        im = SB.scene_photo(1.0 + 4 * i / FPS, W, H, PGOAL, "AI-GENERATED").convert("RGB")   # RA-12 review D4: 4x push rate
        e.stdin.write(np.asarray(im).tobytes())
    e.stdin.close(); e.wait()
    meta["G1"] = dict(asset="goal", src=PGOAL, frames=n, chip="AI-GENERATED under the photo (softblue.scene_photo)")
    print("G1", n, "frames", flush=True)

if want("P1"):
    # B0550 at 60 fps: the options screen with "Generate my goal image" (frame 22), the tap (about 40), his before photo from 41,
    # the scan ("Analyzing your photo", "Mapping muscle groups" ...) to about 35 s. The phone runs at 1.0x until "with your dream
    # body", then the result card (his AI goal picture) carries "in seconds, completely free".
    c = CB["P1"]; n = c["frames"]; a = c["beat"][0]
    t_with = word_after(a, "with")
    nph = int(round((t_with - 0.10 - a) * FPS)); assert 30 <= nph < n - 30, (nph, n)
    SRC0 = 22; WIN = (1320, 2502, 0, 366)
    raw = subprocess.run([L.FF, "-nostdin", "-v", "error", "-ss", f"{(SRC0 - 0.5) / 60:.4f}", "-i", B0550, "-vf",
                          "fps=30000/1001,crop=%d:%d:%d:%d,scale=in_color_matrix=bt709:in_range=tv" % WIN,
                          "-frames:v", str(nph), "-f", "rawvideo", "-pix_fmt", "rgb24", "-"], capture_output=True, check=True).stdout
    scr = np.frombuffer(raw, np.uint8).reshape(-1, WIN[1], WIN[0], 3); assert len(scr) == nph, (len(scr), nph)
    out, log = [], []
    for i in range(nph):
        sf = SRC0 + i * 60 / FPS
        chip = "AI-GENERATED" if sf >= 39 else None
        im, box = S63.phone_card(a + i / FPS, Image.fromarray(S63.square_corners(scr[i])), chip=chip)
        out.append(im); log.append(dict(f=i, b0550_frame=round(sf, 1), chip=chip))
    for i in range(nph, n):
        im = SB.scene_photo(1.0 + 2 * (i - nph) / FPS, W, H, PGOAL, "AI-GENERATED").convert("RGB")
        out.append(im); log.append(dict(f=i, what="result card", chip="AI-GENERATED"))
    L.encode_h264(iter(out), f"{OUT}/P1.mp4", (W, H), crf=15)
    meta["P1"] = dict(asset="B0550", src=B0550, demo_in=SRC0, demo_fps=60, window=WIN, frames=n, phone_frames=nph, phone_box=box,
                      result=PGOAL, chip="AI-GENERATED from B0550 frame 39 (his AI-generated before photo) and on the result", log=log)
    print("P1", n, "frames, phone", nph, flush=True)

if want("T1"):
    # RA-12's T1: the AI Trainer (tour frame 172 on, the tap) on "personalized workout", the Macro Tracker (tour frame 42 on, meal
    # photo, Analyze, the 775 cal breakdown) from "nutrition". Never the Reverse Lunge switch (8.25 s) or the home screen at 5.0 s.
    c = CB["T1"]; n = c["frames"]; a = c["beat"][0]
    t_nut = word_after(a, "nutrition")
    n1 = int(round((t_nut - 0.05 - a) * FPS)); n2 = n - n1
    T0 = min(172, 242 - n1)
    assert T0 >= 160, ("workout part too long for the tour", n1)
    assert 42 + n2 <= 142, ("meal part runs past the 775 cal result", n2)
    import r1_s83_phone as RP
    s1 = RP.frames_of(S63.TOUR, t0=(T0 - 0.5) / FPS, n=n1)
    s2 = RP.frames_of(S63.TOUR, t0=(42 - 0.5) / FPS, n=n2)
    out = []
    for i in range(n):
        scr = s1[i] if i < n1 else s2[i - n1]
        im, box = S63.phone_card(a + i / FPS, Image.fromarray(scr)); out.append(im)
    L.encode_h264(iter(out), f"{OUT}/T1.mp4", (W, H), crf=15)
    meta["T1"] = dict(asset="B0544", src=S63.TOUR, frames=n, cut_at=n1, tour_in=[T0, 42], phone_box=box)
    print("T1", n, "frames, workout", n1, "meal", n2, flush=True)

for k, (src, nn) in REUSE.items():
    if not want(k): continue
    assert CB[k]["frames"] == nn, (k, CB[k]["frames"], nn, "the reused card plays every approved frame, never stretched or cut")
    shutil.copy(src, f"{OUT}/{k}.mp4")
    meta[k] = dict(asset=f"RA-07 R6 card {os.path.basename(src)}", src=src, frames=nn, chip="as approved in RA-07 R6 (unchanged pixels)")
    print(k, nn, "frames (RA-07 approved card, copied)", flush=True)

json.dump(meta, open(f"{OUT}/clips.json", "w"), indent=1, default=str)
# the phone cards' records in the shape the gate scripts read (r1_s94_phonebox.py, r1_gateplan.py)
cj = json.load(open(f"{OUT}/cards.json")) if os.path.exists(f"{OUT}/cards.json") else {}
for k in ("P1", "T1"):
    if k in meta:
        cj[k] = dict(meta[k], id=k, a=CB[k]["beat"][0], n=CB[k]["frames"])
json.dump(cj, open(f"{OUT}/cards.json", "w"), indent=1, default=str)
print("CARDS DONE", sorted(meta))
